export function getInitialLanguage() {
  if (typeof window === 'undefined') return 'AZ';

  try {
    const saved = localStorage.getItem('user_lang') || localStorage.getItem('i18nextLng');
    if (saved) {
      const upper = saved.toUpperCase();
      if (['AZ', 'TR', 'RU', 'EN'].includes(upper)) return upper;
    }
  } catch {}

  try {
    const tz = Intl.DateTimeFormat().resolvedOptions().timeZone || '';
    if (tz === 'Asia/Baku') return 'AZ';
    if (tz === 'Europe/Istanbul' || tz === 'Asia/Istanbul') return 'TR';
    if (
      tz.startsWith('Europe/Moscow') ||
      tz.startsWith('Asia/Yekaterinburg') ||
      tz.startsWith('Asia/Novosibirsk') ||
      tz.startsWith('Asia/Krasnoyarsk') ||
      tz.startsWith('Asia/Irkutsk') ||
      tz.startsWith('Asia/Yakutsk') ||
      tz.startsWith('Asia/Vladivostok') ||
      tz.startsWith('Europe/Minsk') ||
      tz.startsWith('Asia/Almaty')
    ) {
      return 'RU';
    }

    const navLangs = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || '']).map(l => l.toLowerCase());
    for (const l of navLangs) {
      if (l.startsWith('az')) return 'AZ';
      if (l.startsWith('tr')) return 'TR';
      if (l.startsWith('ru')) return 'RU';
      if (l.startsWith('en')) return 'EN';
    }
  } catch {}

  return 'AZ';
}

export async function detectCountryAndSetLanguage(i18nInstance) {
  if (typeof window === 'undefined') return;

  try {
    if (localStorage.getItem('user_lang')) return;
  } catch {}

  try {
    let countryCode = null;
    try {
      const res = await fetch('/api/geo', { cache: 'no-store' });
      if (res.ok) {
        const data = await res.json();
        if (data?.country) countryCode = data.country.toUpperCase();
      }
    } catch {}

    if (!countryCode) {
      try {
        const fbRes = await fetch('https://freeipapi.com/api/json', { signal: AbortSignal.timeout(3000) });
        if (fbRes.ok) {
          const fbData = await fbRes.json();
          if (fbData?.countryCode) countryCode = fbData.countryCode.toUpperCase();
        }
      } catch {}
    }

    if (!countryCode) return;

    let targetLang = 'EN';
    if (countryCode === 'AZ') {
      targetLang = 'AZ';
    } else if (countryCode === 'TR') {
      targetLang = 'TR';
    } else if (['RU', 'BY', 'KZ', 'KG', 'UZ', 'TJ'].includes(countryCode)) {
      targetLang = 'RU';
    } else {
      targetLang = 'EN';
    }

    if (i18nInstance && i18nInstance.language?.toUpperCase() !== targetLang) {
      i18nInstance.changeLanguage(targetLang);
    }
  } catch (err) {
    console.warn('[i18n geo detection error]', err);
  }
}

